#Conversion of Float and Integer
#If the string is taken in an integer/Float form, then it can be converted to an integer/Float using the int() / float() function.
x = "100"
print(type(x))
y = int(x)
print(y)
print(type(y))

#Integer to String
z=str(y)
print(z)
print(type(z))

#Float to String
x=3.14
print(type(x))
y=str(x)
print(y)
print(type(y))

#String to Float
x="3.14"
print(type(x))
y=float(x)
print(y)
print(type(y))